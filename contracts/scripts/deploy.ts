import { ethers, artifacts, network } from "hardhat";
import * as fs from "fs";
import * as path from "path";

/**
 * Deploys KYCRegistry and KYCSoulboundToken to the configured network
 * (intended: Sepolia) and wires the result into the Flutter app:
 *   - writes the deployed address to  lib/config/contract_address.dart
 *   - copies the ABI to              assets/contracts/KYCRegistry.abi.json
 * so the app picks both up automatically with no manual copy/paste.
 *
 * DEPLOY_ONLY=sbt (npm run deploy:sbt:sepolia) redeploys ONLY the badge
 * contract and keeps the registry address already in contract_address.dart.
 * Use it when only KYCSoulboundToken changed: redeploying the registry would
 * orphan every KYC record and access grant stored in the old one.
 */
async function main() {
  const [deployer] = await ethers.getSigners();
  if (!deployer) {
    throw new Error(
      "No deployer signer found. Set DEPLOYER_PRIVATE_KEY in contracts/.env."
    );
  }

  const balance = await ethers.provider.getBalance(deployer.address);
  console.log(`Network:   ${network.name} (chainId ${network.config.chainId})`);
  console.log(`Deployer:  ${deployer.address}`);
  console.log(`Balance:   ${ethers.formatEther(balance)} ETH`);

  // Refuse to run anywhere but Sepolia. Without this guard, a bare
  // `npx hardhat run scripts/deploy.ts` (no --network flag) silently targets
  // the in-process hardhat network (chainId 31337) — whose default accounts are
  // funded, so the balance check below passes — and then overwrites the app's
  // committed contract_address.dart with throwaway local addresses.
  const SEPOLIA_CHAIN_ID = 11155111;
  if (network.config.chainId !== SEPOLIA_CHAIN_ID) {
    throw new Error(
      `Refusing to deploy: expected Sepolia (chainId ${SEPOLIA_CHAIN_ID}), ` +
        `got "${network.name}" (chainId ${network.config.chainId}). ` +
        `Run with: npm run deploy:sepolia`
    );
  }

  if (balance === 0n) {
    throw new Error(
      "Deployer has 0 ETH. Fund it from a Sepolia faucet before deploying."
    );
  }

  const repoRoot = path.resolve(__dirname, "..", "..");
  const assetsDir = path.join(repoRoot, "assets", "contracts");
  const configDir = path.join(repoRoot, "lib", "config");
  fs.mkdirSync(assetsDir, { recursive: true });
  fs.mkdirSync(configDir, { recursive: true });

  // Helper: deploy a contract, print its address, copy its ABI into assets.
  async function deployAndExport(name: string): Promise<string> {
    console.log(`\nDeploying ${name}...`);
    const factory = await ethers.getContractFactory(name);
    const contract = await factory.deploy();
    await contract.waitForDeployment();
    const address = await contract.getAddress();
    console.log(`✅ ${name} deployed to: ${address}`);
    console.log(`   https://sepolia.etherscan.io/address/${address}`);

    const artifact = await artifacts.readArtifact(name);
    const abiFile = path.join(assetsDir, `${name}.abi.json`);
    fs.writeFileSync(abiFile, JSON.stringify(artifact.abi, null, 2));
    console.log(`   Wrote ${path.relative(repoRoot, abiFile)}`);
    return address;
  }

  const dartFile = path.join(configDir, "contract_address.dart");
  const onlySbt = (process.env.DEPLOY_ONLY ?? "").toLowerCase() === "sbt";

  let registryAddress: string;
  if (onlySbt) {
    const current = fs.existsSync(dartFile)
      ? fs.readFileSync(dartFile, "utf8")
      : "";
    const m = current.match(/kKycRegistryAddress\s*=\s*"(0x[0-9a-fA-F]{40})"/);
    if (!m) {
      throw new Error(
        "DEPLOY_ONLY=sbt needs an existing registry address in " +
          "lib/config/contract_address.dart. Run a full deploy first."
      );
    }
    registryAddress = m[1];
    console.log(`\nKeeping KYCRegistry at ${registryAddress} (DEPLOY_ONLY=sbt)`);
  } else {
    registryAddress = await deployAndExport("KYCRegistry");
  }
  const sbtAddress = await deployAndExport("KYCSoulboundToken");

  // Write both addresses into the single Dart config the app reads.
  const dartContent =
    `// GENERATED by contracts/scripts/deploy.ts - do not edit by hand.\n` +
    `// Network: ${network.name} (chainId ${network.config.chainId ?? "?"})\n` +
    `// Deployed: ${new Date().toISOString()}\n` +
    `const String kKycRegistryAddress = "${registryAddress}";\n` +
    `const String kKycSbtAddress = "${sbtAddress}";\n`;
  fs.writeFileSync(dartFile, dartContent);
  console.log(`\n   Wrote ${path.relative(repoRoot, dartFile)}`);

  console.log(
    `\nNext: verify with\n` +
      (onlySbt
        ? ""
        : `  npx hardhat verify --network sepolia ${registryAddress}\n`) +
      `  npx hardhat verify --network sepolia ${sbtAddress}`
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
